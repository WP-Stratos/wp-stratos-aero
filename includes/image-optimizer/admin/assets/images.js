/**
 * Aero — Images screen behaviour
 *
 * Processing runs server-side in a WP-Cron chain; this script only starts
 * tasks, observes progress, and renders the stats band. Reloading or closing
 * the page never interrupts optimization, and an in-flight task is resumed
 * into the UI automatically on load.
 */
/* global jQuery, aeroIo */
(function ($) {
	'use strict';

	if (typeof aeroIo === 'undefined') {
		return;
	}

	var i18n = aeroIo.i18n;
	var bulkRunning = false;
	var bulkTimer = null;
	var logOffset = 0;
	var customRunning = false;
	var customTimer = null;

	function post(action, data) {
		data = data || {};
		data.action = action;
		data.nonce = aeroIo.nonce;
		return $.post(aeroIo.ajaxurl, data);
	}

	function parse(resp) {
		if (typeof resp === 'object' && resp !== null) {
			return resp;
		}
		try {
			return JSON.parse(resp);
		} catch (e) {
			return null;
		}
	}

	function fmtBytes(n) {
		if (n >= 1073741824) { return (n / 1073741824).toFixed(1) + ' GB'; }
		if (n >= 1048576) { return (n / 1048576).toFixed(1) + ' MB'; }
		if (n >= 1024) { return (n / 1024).toFixed(1) + ' KB'; }
		return n + ' B';
	}

	// ═══ Stats band (donut + tiles, same pattern as the Optimization screen) ══
	// The engine caches aggregated stats behind a freshness transient that is
	// cleared after every optimization batch. Entering through start_stats is
	// what honors that gate — a cached answer is fresh, anything else means
	// recompute. Never trust the bare get_stats "done" snapshot on its own.

	function renderBand(d) {
		var webpCount = d.converted_webp || 0;
		var avifCount = d.converted_avif || 0;
		var optimized = Math.max(webpCount, avifCount);

		$('#aero-io-donut-total').text(optimized.toLocaleString());

		var savedWebp = Math.max(0, (d.original_total_webp || 0) - (d.webp_total || 0));
		var savedAvif = Math.max(0, (d.original_total_avif || 0) - (d.avif_total || 0));
		$('#aero-io-stat-saved').text(fmtBytes(savedWebp + savedAvif));

		var origBytes = (d.original_total_webp || 0) + (d.original_total_avif || 0);
		var ratio = origBytes > 0 ? Math.round(((savedWebp + savedAvif) / origBytes) * 100) : 0;
		$('#aero-io-stat-ratio').text(ratio + '%');

		// Donut: WebP vs AVIF share of generated bytes — the same composition
		// semantic as the Optimization screen's CSS/JS ring.
		var webpBytes = d.webp_total || 0;
		var avifBytes = d.avif_total || 0;
		var totalBytes = webpBytes + avifBytes;
		$('#aero-io-legend-webp').text(fmtBytes(webpBytes));
		$('#aero-io-legend-avif').text(fmtBytes(avifBytes));

		var C = 2 * Math.PI * 48;
		var webpFrac = totalBytes > 0 ? webpBytes / totalBytes : 0;
		var avifFrac = totalBytes > 0 ? avifBytes / totalBytes : 0;
		var gap = (webpFrac > 0 && avifFrac > 0) ? 0.005 : 0;
		var webpEl = document.getElementById('aero-io-donut-webp');
		var avifEl = document.getElementById('aero-io-donut-avif');
		if (webpEl && avifEl) {
			webpEl.style.strokeDasharray = (Math.max(webpFrac - gap, 0) * C) + ' ' + C;
			webpEl.style.strokeDashoffset = 0;
			avifEl.style.strokeDasharray = (Math.max(avifFrac - gap, 0) * C) + ' ' + C;
			avifEl.style.strokeDashoffset = -(webpFrac * C);
		}
	}

	function bandEmpty() {
		$('#aero-io-donut-total').text('0');
		$('#aero-io-legend-webp').text('0 B');
		$('#aero-io-legend-avif').text('0 B');
		$('#aero-io-stat-saved').text('0 B');
		$('#aero-io-stat-ratio').text('0%');
	}

	var statsBusy = false;
	var executingStreak = 0;

	function loadStats() {
		if (statsBusy) { return; }
		statsBusy = true;
		executingStreak = 0;
		post('aero_io_start_stats').done(function (resp) {
			var r = parse(resp);
			if (r && r.success && r.data && r.data.status === 'cached') {
				statsBusy = false;
				renderBand(r.data.cached || {});
				return;
			}
			// Recompute path: drive continue/get until done.
			statsStep(0);
		}).fail(function () {
			statsBusy = false;
			bandEmpty();
		});
	}

	function statsStep(attempt) {
		if (attempt > 60) { statsBusy = false; bandEmpty(); return; }
		post('aero_io_get_stats').done(function (resp) {
			var r = parse(resp);
			if (!r || !r.success || !r.data) { statsBusy = false; bandEmpty(); return; }
			var st = r.data.status;
			if (st === 'done' || st === 'cached') {
				statsBusy = false;
				renderBand(r.data.cached || r.data);
			} else if (st === 'in_progress') {
				executingStreak = 0;
				post('aero_io_continue_stats').always(function () {
					setTimeout(function () { statsStep(attempt + 1); }, 1200);
				});
			} else if (st === 'executing') {
				// A crashed continue request leaves the progress state stuck
				// on "running" forever; after ~10s of no movement, hard-reset
				// once and start over.
				executingStreak++;
				if (executingStreak >= 8) {
					statsBusy = false;
					post('aero_io_reset_stats').always(function () { loadStats(); });
					return;
				}
				setTimeout(function () { statsStep(attempt + 1); }, 1200);
			} else {
				// not_started can only appear if the start call raced a reset;
				// re-enter through start.
				statsBusy = false;
				loadStats();
			}
		}).fail(function () {
			statsBusy = false;
			bandEmpty();
		});
	}

	function refreshStats() {
		// Hard refresh after optimization work: throw away the cached
		// aggregate so the recount reflects the new meta rows.
		post('aero_io_reset_stats').always(function () {
			statsBusy = false;
			loadStats();
		});
	}

	// ═══ Bulk optimization (media library) ═══════════════════════════════
	// The cron chain owns processing. "Run" endpoints only re-arm the chain,
	// so the poll loop is pure observation: continue → keep polling,
	// finished → done, batch boundary → nudge the chain, failed+timeout →
	// nudge the chain.

	function setBulkUi(title, pct, text, sub) {
		$('#aero-io-bulk-title').text(title);
		if (pct !== null) {
			pct = Math.max(0, Math.min(100, pct));
			$('#aero-io-bulk-pct').text(pct + '%');
			$('#aero-io-bulk-fill').css('width', pct + '%');
		}
		if (text !== null) {
			$('#aero-io-bulk-text').text(text);
		}
		$('#aero-io-bulk-sub').text(sub || '');
	}

	function lockButtons() {
		$('#aero-io-scan, #aero-io-start, #aero-io-force').prop('disabled', true);
	}
	function unlockButtons() {
		$('#aero-io-scan, #aero-io-start, #aero-io-force').prop('disabled', false);
		$('#aero-io-cancel').hide();
	}

	function enterRunningUi(title) {
		bulkRunning = true;
		lockButtons();
		$('#aero-io-cancel').show();
		$('#aero-io-counts').show();
		setBulkUi(title, null, '', i18n.bgNote);
	}

	var lastScanFound = null;

	function runScan(force, offset, done) {
		post('aero_io_start_scan', { force: force ? '1' : '0', offset: offset }).done(function (resp) {
			var r = parse(resp);
			if (!r || r.result !== 'success') {
				setBulkUi('Error', null, (r && r.error) || i18n.failed, '');
				unlockButtons();
				return;
			}
			var pct = typeof r.progress_percent !== 'undefined' ? parseInt(r.progress_percent, 10) : null;
			setBulkUi(i18n.scanning, pct, r.progress_text || '', '');
			if (r.finished) {
				lastScanFound = parseInt(r.found || 0, 10);
				setBulkUi(i18n.scanDone, 100, (r.progress_text || '') + ' — ' + lastScanFound + ' to optimize', '');
				if (done) { done(); } else { unlockButtons(); }
			} else {
				runScan(force, r.offset || 0, done);
			}
		}).fail(function () {
			setBulkUi('Error', null, i18n.failed, '');
			unlockButtons();
		});
	}

	$('#aero-io-scan').on('click', function () {
		lockButtons();
		$('#aero-io-bulk-panel').removeClass('is-complete');
		setBulkUi(i18n.scanning, 0, '', '');
		runScan(false, 0, function () {
			unlockButtons();
			refreshStats();
			if (lastScanFound === 0) { markComplete(); }
		});
	});

	// Resting "everything is done" state: solid bar, no percentage reset.
	function markComplete() {
		$('#aero-io-bulk-panel').addClass('is-complete');
		setBulkUi(i18n.allOptimized, 100, i18n.nothingLeft, '');
	}

	function startBulk(force) {
		$('#aero-io-bulk-panel').removeClass('is-complete');
		enterRunningUi(i18n.scanning);
		setBulkUi(i18n.scanning, 0, '', '');
		logOffset = 0;
		$('#aero-io-live-log').empty();

		runScan(force, 0, function () {
			post('aero_io_init_bulk', { force: force ? '1' : '0' }).done(function (resp) {
				var r = parse(resp);
				if (!r || r.result !== 'success') {
					var msg = (r && r.error) || i18n.failed;
					setBulkUi(r && r.no_unoptimized_images ? i18n.noImages : 'Error', 0, msg, '');
					bulkRunning = false;
					unlockButtons();
					refreshStats();
					return;
				}
				// The server armed the cron chain during init; observe.
				setBulkUi(i18n.optimizing, 0, '', i18n.bgNote);
				schedulePoll(1200);
			}).fail(function () {
				setBulkUi('Error', null, i18n.failed, '');
				bulkRunning = false;
				unlockButtons();
			});
		});
	}

	function nudgeChain() {
		post('aero_io_run_optimize');
	}

	function schedulePoll(delay) {
		if (bulkTimer) { clearTimeout(bulkTimer); }
		bulkTimer = setTimeout(pollBulk, delay);
	}

	var pollTicks = 0;

	function pollBulk() {
		if (!bulkRunning) { return; }
		post('aero_io_get_progress').done(function (resp) {
			var r = parse(resp);
			if (!r) { schedulePoll(2500); return; }

			if (r.result === 'success') {
				var pct = typeof r.progress_percent !== 'undefined' ? parseInt(r.progress_percent, 10) : null;
				setBulkUi(i18n.optimizing, pct, r.progress_text || '', r.sub_progress_text || i18n.bgNote);
				$('#aero-io-count-ok').text(r.optimized || 0);
				$('#aero-io-count-rem').text(r.remaining || 0);
				$('#aero-io-count-fail').text(r.errors || 0);
				pullLog();

				// The engine clears the stats freshness gate after every
				// batch, so a periodic pass through loadStats() recomputes
				// live numbers while the run progresses.
				pollTicks++;
				if (pollTicks % 6 === 0) { loadStats(); }

				if (r.finished) {
					stopBulk(i18n.done, r.progress_text || '');
					setBulkUi(i18n.done, 100, r.progress_text || '', '');
					$('#aero-io-bulk-panel').addClass('is-complete');
					if (r.tree_size) { $('#aero-io-stat-tree').text(r.tree_size); }
					refreshStats();
				} else {
					if (!r.continue) { nudgeChain(); }
					schedulePoll(2000);
				}
			} else if (r.timeout) {
				nudgeChain();
				schedulePoll(2000);
			} else {
				stopBulk('Error', r.error || i18n.failed);
			}
		}).fail(function () {
			schedulePoll(3000);
		});
	}

	function stopBulk(title, text) {
		bulkRunning = false;
		if (bulkTimer) { clearTimeout(bulkTimer); bulkTimer = null; }
		setBulkUi(title, null, text, '');
		unlockButtons();
	}

	function pullLog() {
		if (!$('#aero-io-live-log').is(':visible')) { return; }
		post('aero_io_get_task_log', { offset: logOffset }).done(function (resp) {
			var r = parse(resp);
			if (r && r.result === 'success' && typeof r.content === 'string' && r.content.length) {
				logOffset = r.offset || logOffset;
				var $log = $('#aero-io-live-log');
				$log.append(document.createTextNode(r.content));
				$log.scrollTop($log[0].scrollHeight);
			}
		});
	}

	$('#aero-io-start').on('click', function () { startBulk(false); });
	$('#aero-io-force').on('click', function () {
		if (window.confirm(i18n.confirmForce)) { startBulk(true); }
	});
	$('#aero-io-cancel').on('click', function () {
		post('aero_io_cancel_bulk').always(function () {
			stopBulk(i18n.cancelled, '');
			setBulkUi(i18n.cancelled, null, '', '');
			refreshStats();
		});
	});
	$('#aero-io-toggle-log').on('click', function () {
		var $log = $('#aero-io-live-log');
		$log.toggle();
		if ($log.is(':visible')) { pullLog(); }
	});

	// ═══ Delivery test ═══════════════════════════════════════════════════
	$('#aero-io-test-delivery').on('click', function () {
		var $r = $('#aero-io-test-result');
		$r.attr('class', 'aero-io-test-result').text('…');
		post('aero_io_test_rewrite').done(function (resp) {
			var r = parse(resp);
			if (!r || r.result !== 'success') {
				$r.attr('class', 'aero-io-test-result aero-io-err').text(i18n.failed);
				return;
			}
			var picture = (r.mode === 'picture');
			if (r.working) {
				$r.attr('class', 'aero-io-test-result aero-io-ok').text('✓ ' + (picture ? i18n.testWorkingPic : i18n.testWorkingRw));
			} else {
				$r.attr('class', 'aero-io-test-result aero-io-err').text('✕ ' + (picture ? i18n.testBrokenPic : i18n.testBrokenRw));
			}
		}).fail(function () {
			$r.attr('class', 'aero-io-test-result aero-io-err').text(i18n.failed);
		});
	});

	// ═══ Quality preset toggle ═══════════════════════════════════════════
	$('#aero-io-quality').on('change', function () {
		$('.aero-io-custom-q').toggle($(this).val() === 'custom');
	});

	// ═══ Restore ═════════════════════════════════════════════════════════
	$('#aero-io-restore').on('click', function () {
		if (!window.confirm(i18n.confirmRestore)) { return; }
		var $btn = $(this).prop('disabled', true);
		post('aero_io_delete_files').done(function (resp) {
			var r = parse(resp);
			$('#aero-io-restore-result')
				.attr('class', r && r.result === 'success' ? 'aero-io-ok' : 'aero-io-err')
				.text(r && r.result === 'success' ? i18n.restoreDone : i18n.failed);
			$('#aero-io-stat-tree').text('0 B');
			refreshStats();
		}).always(function () {
			$btn.prop('disabled', false);
		});
	});

	// ═══ Custom folders ══════════════════════════════════════════════════
	function renderCustomRows(folders) {
		var $body = $('#aero-io-custom-body').empty();
		$.each(folders, function (_, path) {
			var $tr = $('<tr>').attr('data-path', path);
			$tr.append($('<td>').append($('<code>').text(path)));
			$tr.append($('<td>').append($('<button type="button" class="aero-btn aero-btn-danger aero-btn-sm aero-io-custom-remove">Remove</button>')));
			$body.append($tr);
		});
		$('#aero-io-custom-table').toggle(folders.length > 0);
	}

	$('#aero-io-custom-add').on('click', function () {
		var path = $.trim($('#aero-io-custom-path').val());
		if (!path) { return; }
		post('aero_io_add_custom_folder', { path: path }).done(function (resp) {
			var r = parse(resp);
			if (r && r.result === 'success') {
				$('#aero-io-custom-path').val('');
				renderCustomRows(r.folders || []);
				$('#aero-io-custom-text').text(i18n.folderAdded);
			} else {
				$('#aero-io-custom-text').text((r && r.error) || i18n.failed);
			}
		});
	});

	$(document).on('click', '.aero-io-custom-remove', function () {
		var path = $(this).closest('tr').attr('data-path');
		post('aero_io_remove_custom_folder', { path: path }).done(function (resp) {
			var r = parse(resp);
			if (r && r.result === 'success') {
				renderCustomRows(r.folders || []);
				$('#aero-io-custom-text').text(i18n.folderRemoved);
			}
		});
	});

	function setCustomUi(title, pct, text) {
		$('#aero-io-custom-title').text(title);
		if (pct !== null) {
			pct = Math.max(0, Math.min(100, pct));
			$('#aero-io-custom-pct').text(pct + '%');
			$('#aero-io-custom-fill').css('width', pct + '%');
		}
		if (text !== null) { $('#aero-io-custom-text').text(text); }
	}

	$('#aero-io-custom-scan').on('click', function () {
		var $btn = $(this).prop('disabled', true);
		setCustomUi(i18n.scanning, 0, '');
		post('aero_io_scan_custom').done(function (resp) {
			var r = parse(resp);
			if (r && r.result === 'success') {
				setCustomUi(i18n.scanDone, 0, r.found + ' ' + i18n.customScanned);
			} else {
				setCustomUi('Error', 0, (r && r.error) || i18n.failed);
			}
		}).always(function () { $btn.prop('disabled', false); });
	});

	function enterCustomRunningUi(title) {
		customRunning = true;
		$('#aero-io-custom-start, #aero-io-custom-scan').prop('disabled', true);
		setCustomUi(title, null, i18n.bgNote);
	}

	$('#aero-io-custom-start').on('click', function () {
		enterCustomRunningUi(i18n.optimizing);
		setCustomUi(i18n.optimizing, 0, '');
		post('aero_io_init_custom_bulk', { force: '0' }).done(function (resp) {
			var r = parse(resp);
			if (!r || r.result !== 'success') {
				stopCustom('Error', (r && r.error) || i18n.failed);
				return;
			}
			scheduleCustomPoll(1200);
		}).fail(function () {
			stopCustom('Error', i18n.failed);
		});
	});

	function nudgeCustomChain() {
		post('aero_io_run_custom_optimize');
	}

	function scheduleCustomPoll(delay) {
		if (customTimer) { clearTimeout(customTimer); }
		customTimer = setTimeout(pollCustom, delay);
	}

	function pollCustom() {
		if (!customRunning) { return; }
		post('aero_io_get_custom_progress').done(function (resp) {
			var r = parse(resp);
			if (!r) { scheduleCustomPoll(2500); return; }

			if (r.result === 'success') {
				var pct = typeof r.percent !== 'undefined' ? parseInt(r.percent, 10) : null;
				setCustomUi(i18n.optimizing, pct, r.log || i18n.bgNote);
				if (r.finished) {
					stopCustom(i18n.customDone, r.log || '');
					setCustomUi(i18n.customDone, 100, r.log || '');
					refreshStats();
				} else {
					if (!r.continue) { nudgeCustomChain(); }
					scheduleCustomPoll(2000);
				}
			} else if (r.timeout) {
				nudgeCustomChain();
				scheduleCustomPoll(2000);
			} else {
				// An absent task also reports failed — treat as terminal.
				stopCustom('Done', r.error || i18n.failed);
			}
		}).fail(function () {
			scheduleCustomPoll(3000);
		});
	}

	function stopCustom(title, text) {
		customRunning = false;
		if (customTimer) { clearTimeout(customTimer); customTimer = null; }
		setCustomUi(title, null, text);
		$('#aero-io-custom-start, #aero-io-custom-scan').prop('disabled', false);
	}

	// ═══ Logs ════════════════════════════════════════════════════════════
	function loadLogs() {
		post('aero_io_get_logs_list').done(function (resp) {
			var r = parse(resp);
			var logs = (r && r.logs) || [];
			var $body = $('#aero-io-logs-body').empty();
			$('#aero-io-logs-table').toggle(logs.length > 0);
			$('#aero-io-logs-empty').toggle(logs.length === 0);
			$.each(logs, function (_, log) {
				var $tr = $('<tr>').attr('data-file', log.file);
				$tr.append($('<td>').append($('<code>').text(log.file)));
				$tr.append($('<td>').text(log.time));
				$tr.append($('<td>').text(log.size));
				var $actions = $('<td class="aero-io-log-actions">');
				$actions.append($('<button type="button" class="aero-btn aero-btn-ghost aero-btn-sm aero-io-log-view">View</button>'));
				$actions.append($('<button type="button" class="aero-btn aero-btn-ghost aero-btn-sm aero-io-log-download">Download</button>'));
				$actions.append($('<button type="button" class="aero-btn aero-btn-danger aero-btn-sm aero-io-log-delete">Delete</button>'));
				$tr.append($actions);
				$body.append($tr);
			});
		});
	}

	$('#aero-io-logs-refresh').on('click', loadLogs);

	$('#aero-io-logs-clear').on('click', function () {
		if (!window.confirm(i18n.confirmLogs)) { return; }
		post('aero_io_delete_all_logs').always(function () {
			$('#aero-io-log-view').hide().empty();
			loadLogs();
		});
	});

	$(document).on('click', '.aero-io-log-view', function () {
		var file = $(this).closest('tr').attr('data-file');
		post('aero_io_view_log', { file: file }).done(function (resp) {
			var r = parse(resp);
			if (r && r.result === 'success') {
				$('#aero-io-log-view').text(r.content).show();
			}
		});
	});

	$(document).on('click', '.aero-io-log-download', function () {
		var file = $(this).closest('tr').attr('data-file');
		window.location = aeroIo.ajaxurl + '?action=aero_io_download_log&nonce=' + encodeURIComponent(aeroIo.nonce) + '&file=' + encodeURIComponent(file);
	});

	$(document).on('click', '.aero-io-log-delete', function () {
		var file = $(this).closest('tr').attr('data-file');
		post('aero_io_delete_log', { file: file }).always(function () {
			$('#aero-io-log-view').hide().empty();
			loadLogs();
		});
	});

	// ═══ Master switch ═══════════════════════════════════════════════════
	function applyEnabledState(on) {
		var $m = $('.aero-io-master');
		$m.toggleClass('is-on', !!on).toggleClass('is-off', !on);
		$('#aero-io-scan, #aero-io-start, #aero-io-force, #aero-io-custom-scan, #aero-io-custom-start')
			.prop('disabled', !on);
	}

	$('#aero-io-master-toggle').on('change', function () {
		var on = $(this).is(':checked');
		var $t = $(this).prop('disabled', true);
		$('#aero-io-master-sub').text(on ? i18n.toggleOn : i18n.toggleOff);
		post('aero_io_toggle_enabled', { enabled: on ? '1' : '0' }).always(function () {
			// State touches hook registration on both the front end and the
			// admin, so reload rather than guess at a half-applied page.
			window.location.reload();
		}).fail(function () {
			$t.prop('disabled', false);
		});
	});

	// ═══ Stylesheet cache ════════════════════════════════════════════════
	$('#aero-io-clear-css').on('click', function () {
		var $btn = $(this).prop('disabled', true);
		var $r = $('#aero-io-test-result').attr('class', 'aero-io-test-result').text('…');
		post('aero_io_clear_css_cache').done(function () {
			$r.attr('class', 'aero-io-test-result aero-io-ok').text('✓ ' + i18n.cssCleared);
		}).fail(function () {
			$r.attr('class', 'aero-io-test-result aero-io-err').text(i18n.failed);
		}).always(function () {
			$btn.prop('disabled', false);
		});
	});

	// ═══ Image URL replace ═══════════════════════════════════════════════
	function urlPair() {
		return {
			from: $.trim($('#aero-io-url-from').val()),
			to: $.trim($('#aero-io-url-to').val())
		};
	}

	function describeTables(tables) {
		var parts = [];
		$.each(tables || {}, function (name, count) {
			parts.push(count + ' × ' + name);
		});
		return parts.length ? ' (' + parts.join(', ') + ')' : '';
	}

	$('#aero-io-url-from, #aero-io-url-to').on('input', function () {
		$('#aero-io-url-apply').prop('disabled', true);
	});

	$('#aero-io-url-scan').on('click', function () {
		var pair = urlPair();
		var $btn = $(this).prop('disabled', true);
		var $r = $('#aero-io-url-result').attr('class', 'aero-io-test-result').text(i18n.replaceScan);

		post('aero_io_scan_url_replace', pair).done(function (resp) {
			var r = parse(resp);
			if (!r || r.result !== 'success') {
				$r.attr('class', 'aero-io-test-result aero-io-err').text((r && r.error) || i18n.failed);
				return;
			}
			if (!r.rows) {
				$r.attr('class', 'aero-io-test-result aero-io-warn').text(i18n.replaceNone);
				return;
			}
			$r.attr('class', 'aero-io-test-result aero-io-ok')
				.text('✓ ' + r.rows + ' row(s) reference this image' + describeTables(r.tables));
			$('#aero-io-url-apply').prop('disabled', false);
		}).fail(function () {
			$r.attr('class', 'aero-io-test-result aero-io-err').text(i18n.failed);
		}).always(function () {
			$btn.prop('disabled', false);
		});
	});

	$('#aero-io-url-apply').on('click', function () {
		if (!window.confirm(i18n.replaceConfirm)) { return; }
		var pair = urlPair();
		var $btn = $(this).prop('disabled', true);
		var $r = $('#aero-io-url-result').attr('class', 'aero-io-test-result').text('…');

		post('aero_io_apply_url_replace', pair).done(function (resp) {
			var r = parse(resp);
			if (!r || r.result !== 'success') {
				$r.attr('class', 'aero-io-test-result aero-io-err').text((r && r.error) || i18n.failed);
				$btn.prop('disabled', false);
				return;
			}
			$r.attr('class', 'aero-io-test-result aero-io-ok')
				.text('✓ ' + i18n.replaceApplied + ' ' + r.rows + ' row(s) updated' + describeTables(r.tables));
		}).fail(function () {
			$r.attr('class', 'aero-io-test-result aero-io-err').text(i18n.failed);
			$btn.prop('disabled', false);
		});
	});

	// ═══ Boot ════════════════════════════════════════════════════════════
	$(function () {
		applyEnabledState(aeroIo.enabled);
		loadStats();
		loadLogs();

		// Resume any task the cron chain is still driving.
		if (aeroIo.mediaActive) {
			enterRunningUi(i18n.resumed);
			schedulePoll(400);
		}
		if (aeroIo.customActive) {
			enterCustomRunningUi(i18n.resumed);
			scheduleCustomPoll(400);
		}
	});
})(jQuery);
